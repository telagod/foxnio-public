import test from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, realpathSync, writeFileSync, rmSync, existsSync, statSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
const executable = fileURLToPath(new URL('../../bin/omp-web.js', import.meta.url));
const packageDirectory = fileURLToPath(new URL('../../', import.meta.url));
test('data CLI requires offline assertion, retains legacy data, and exports only protected consistent backups', t => {
  const home = realpathSync.native(mkdtempSync(join(tmpdir(), 'fox-data-cli-'))), agent = join(home, '.omp', 'agent');
  mkdirSync(agent, { recursive: true });
  const projects = join(agent, 'projects.json');
  const project = join(home, 'project'); mkdirSync(project);
  writeFileSync(projects, JSON.stringify({ version: 1, projects: [{ path: project, addedAt: '2026-01-01T00:00:00Z', hidden: false }] }));
  t.after(() => rmSync(home, { recursive: true, force: true }));
  const env = { ...process.env, HOME: home, USERPROFILE: home, PI_CODING_AGENT_DIR: agent, PI_CONFIG_DIR: '.omp', XDG_DATA_HOME: join(home, 'unused-xdg'), OMP_WEB_PACKAGE_DIR: packageDirectory };
  const cli = (...args) => spawnSync(process.execPath, [executable, 'data', ...args], { env, encoding: 'utf8' });
  const status = cli('status');
  assert.equal(status.status, 1, status.stderr);
  assert.ok(status.stdout.trim(), `status produced no JSON; stderr: ${status.stderr}`);
  assert.equal(JSON.parse(status.stdout).error.code, 'migration_required');
  assert.equal(cli('migrate').status, 2);
  assert.equal(existsSync(join(agent, 'omp-web', 'app.db')), false);
  const migrated = cli('migrate', '--offline'); assert.equal(migrated.status, 0, migrated.stderr);
  assert.equal(JSON.parse(migrated.stdout).alreadyMigrated, false);
  assert.equal(existsSync(projects), true);
  const backed = cli('backup'); assert.equal(backed.status, 0, backed.stderr);
  const result = JSON.parse(backed.stdout);
  assert.ok(result.path.startsWith(join(agent, 'omp-web', 'app.db.backup-')));
  const backupStat = statSync(result.path);
  assert.equal(backupStat.isFile(), true);
  // Windows stat modes do not represent POSIX owner/group permissions.
  if (process.platform !== 'win32') assert.equal(backupStat.mode & 0o777, 0o600);
  const arbitrary = join(home, 'arbitrary', 'export.db');
  assert.equal(cli('backup', arbitrary).status, 2);
  assert.equal(existsSync(arbitrary), false);
  const rebuilt = cli('rebuild-index'); assert.equal(rebuilt.status, 0, rebuilt.stderr);
  assert.equal(JSON.parse(rebuilt.stdout).complete, true);
});
